#include<stdio.h>
int main()
{
	int i;
	printf("print 1 to 10 numbers\n");
	//for loop//
	for (i=1;i<=10;i++)
	{
		printf("\n%d",i);
	}
	//while loop//
	i=1;
	while(i<=10);
	{
	printf("%d",i);
	}	i++;
	printf("\n");
	//do while loop//
	i=1;
	do{
		printf("%d",i);
	
	i++;
	}while(i<=10);
}
